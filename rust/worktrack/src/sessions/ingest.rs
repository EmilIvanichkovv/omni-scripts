//! Claude Code transcript ingestion (spec 6.1 scan, 6.2 parsing, 6.3 linking at ingest time).
//!
//! The parser is tolerant: one JSON object per line, unknown `type` values and fields ignored,
//! malformed lines skipped and counted. Parsing is incremental: `session_files` stores the byte
//! offset reached per transcript; a scan compares `(path, size, mtime)` and parses only new
//! bytes. A partial last line (no trailing `\n` yet) is not consumed, so the offset never moves
//! past it. A file that shrank is reparsed from offset 0.
//!
//! Public API (all SQL functions take `&rusqlite::Connection`; run them on the DB writer):
//! - [`refresh`]: one call per local reload. Runs [`scan`], [`drain_queue`],
//!   [`mark_idle_ended`] and [`super::link::link_unlinked`] in that order.
//! - [`scan`]: parse new bytes of every `<projects_dir>/*/*.jsonl` (subagent transcripts in
//!   deeper directories are not sessions and are skipped).
//! - [`ingest_file`]: parse one transcript (used by `scan` and `drain_queue`).
//! - [`drain_queue`]: consume `session_queue` rows written by the hook, mark sessions ended.
//! - [`mark_idle_ended`]: end sessions whose file has not changed for 30 min.
//! - [`load_sessions`] / [`load_session`]: `Session`s with links, for the UI
//!   (`AppEvent::SessionsUpdated`).
//! - [`Transcript`]: the pure incremental parser (no IO).
//!
//! Sessions whose `cwd` is the summarizer directory are never stored (recursion guard, 6.4).

